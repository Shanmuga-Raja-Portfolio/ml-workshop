#!/usr/bin/env python3
"""Bootstrap the ML workshop on any machine.

Stdlib-only, Python 3.10+ - this runs BEFORE any project dependencies exist,
including on a bare system Python. It:

  1. Finds `uv` (PATH, common install dirs) or installs it.
  2. Detects the hardware accelerator (NVIDIA CUDA / AMD ROCm / Apple MPS / CPU)
     and writes workshop_config.json at the repo root (see CONFIG CONTRACT below).
  3. Runs `uv sync`, injecting the correct PyTorch wheel index for this machine.
  4. With --download, prefetches every dataset/model in downloads/manifest.json
     via tools/fetch_data.py.

Usage:
    python tools/bootstrap.py [--cpu] [--download]

CONFIG CONTRACT (workshop_config.json, gitignored):
    {"device": "cuda"|"mps"|"cpu",
     "accelerator": "cuda"|"rocm"|"mps"|"cpu",
     "dtype": "bfloat16"|"float16"|"float32",
     "vram_gb": <float|null>,
     "tier": "gpu-high"|"gpu-low"|"cpu"}
    tier: vram_gb >= 12 -> "gpu-high"; 0 < vram_gb < 12 -> "gpu-low"; else "cpu".
    dtype: cuda -> bfloat16 (float16 on pre-Ampere GPUs), mps -> float16,
           cpu -> float32.
"""

from __future__ import annotations

import argparse
import json
import os
import platform
import shutil
import subprocess
import sys
import sysconfig
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
CONFIG_PATH = REPO_ROOT / "workshop_config.json"
PYPROJECT_PATH = REPO_ROOT / "pyproject.toml"
LOCK_PATH = REPO_ROOT / "uv.lock"
UV_TOML_PATH = REPO_ROOT / "uv.toml"  # legacy: earlier bootstraps generated this

# PyTorch wheel indexes, chosen per detected accelerator.
#
# Why a generated block in pyproject.toml (not uv.toml / UV_INDEX):
#   * The PyTorch indexes mirror third-party packages with STALE versions
#     (e.g. requests 2.28.1, certifi 2022). A supplementary non-explicit index
#     (uv.toml [[index]] or UV_INDEX) is searched for EVERY package, so those
#     stale mirrors silently downgrade half the environment.
#   * Scoping an index to just torch/torchvision requires `explicit = true` +
#     [tool.uv.sources], and uv only accepts `sources` in pyproject.toml
#     ("only applicable in the context of a project"); `torch-backend` is
#     uv-pip-only. So the committed pyproject stays platform-neutral and
#     bootstrap rewrites the marked block below per machine.
PYTORCH_INDEX = {
    # cu128 works for Ada (sm_89) and Blackwell (sm_120). Pre-Ada cards
    # (sm < 89) may prefer the cu126 build; keeping it simple per plan -
    # change here if you hit "no kernel image" errors on older GPUs.
    "cuda": "https://download.pytorch.org/whl/cu128",
    "rocm": "https://download.pytorch.org/whl/rocm6.3",
    # mps / cpu: default PyPI wheels already ship MPS (macOS arm64) and CPU
    # builds, so no extra index is needed.
}

BLOCK_BEGIN = "# --- BEGIN machine-local PyTorch config (generated by tools/bootstrap.py; do not commit) ---"
BLOCK_END = "# --- END machine-local PyTorch config ---"


def log(msg: str) -> None:
    print(f"[bootstrap] {msg}", flush=True)


# ---------------------------------------------------------------- uv


def find_uv() -> str | None:
    """Locate a uv executable on PATH or in well-known install locations."""
    on_path = shutil.which("uv")
    if on_path:
        return on_path
    candidates = []
    localappdata = os.environ.get("LOCALAPPDATA")
    if localappdata:
        candidates.append(Path(localappdata) / "hermes" / "bin" / "uv.exe")
    userprofile = os.environ.get("USERPROFILE")
    if userprofile:
        candidates.append(Path(userprofile) / ".local" / "bin" / "uv.exe")
    candidates.append(Path.home() / ".local" / "bin" / "uv")
    candidates.append(Path.home() / ".cargo" / "bin" / "uv")
    for cand in candidates:
        if cand.is_file():
            return str(cand)
    return None


def install_uv() -> str:
    """Install uv, preferring pip into the current interpreter's Scripts dir."""
    log("uv not found - installing it now.")
    pip_attempts = []
    if platform.system() == "Windows" and shutil.which("py"):
        pip_attempts.append(["py", "-m", "pip", "install", "--user", "uv"])
    pip_attempts.append([sys.executable, "-m", "pip", "install", "--user", "uv"])
    for cmd in pip_attempts:
        try:
            subprocess.run(cmd, check=True)
        except (subprocess.CalledProcessError, OSError) as exc:
            log(f"  {' '.join(cmd)} failed ({exc}); trying next method.")
            continue
        # pip console scripts land in the interpreter's scripts dir (or the
        # --user scripts dir). Check both, then PATH again.
        scripts_dirs = [sysconfig.get_path("scripts")]
        try:
            scripts_dirs.append(sysconfig.get_path("scripts", scheme="nt_user" if os.name == "nt" else "posix_user"))
        except Exception:
            pass
        exe = "uv.exe" if os.name == "nt" else "uv"
        for d in scripts_dirs:
            cand = Path(d) / exe
            if cand.is_file():
                return str(cand)
        found = find_uv()
        if found:
            return found

    # Last resort: the official standalone installer script.
    log("pip install failed; falling back to the official uv installer script.")
    if os.name == "nt":
        subprocess.run(
            ["powershell", "-ExecutionPolicy", "ByPass", "-c",
             "irm https://astral.sh/uv/install.ps1 | iex"],
            check=True,
        )
    else:
        subprocess.run(
            ["sh", "-c", "curl -LsSf https://astral.sh/uv/install.sh | sh"],
            check=True,
        )
    found = find_uv()
    if not found:
        sys.exit("[bootstrap] ERROR: uv installation succeeded but uv is not locatable. "
                 "Install manually: https://docs.astral.sh/uv/getting-started/installation/")
    return found


# ------------------------------------------------------- accelerator probe


def _run_quiet(cmd: list[str], timeout: int = 15) -> str | None:
    try:
        out = subprocess.run(cmd, capture_output=True, text=True, timeout=timeout)
    except (OSError, subprocess.TimeoutExpired):
        return None
    return out.stdout if out.returncode == 0 else None


def detect_nvidia() -> dict | None:
    """Parse `nvidia-smi` for name, total VRAM (GB), and compute capability."""
    if not shutil.which("nvidia-smi"):
        return None
    out = _run_quiet([
        "nvidia-smi",
        "--query-gpu=name,memory.total,compute_cap",
        "--format=csv,noheader,nounits",
    ])
    if not out:
        return None
    line = out.strip().splitlines()[0]
    parts = [p.strip() for p in line.split(",")]
    if len(parts) < 3:
        return None
    name, mem_mib, cap = parts[0], parts[1], parts[2]
    try:
        vram_gb = round(float(mem_mib) / 1024.0, 1)
    except ValueError:
        vram_gb = None
    try:
        cap_major = int(float(cap))
    except ValueError:
        cap_major = 0
    # Pre-Ampere (compute capability < 8.0) GPUs lack bfloat16 hardware.
    dtype = "bfloat16" if cap_major >= 8 else "float16"
    return {
        "device": "cuda",
        "accelerator": "cuda",
        "dtype": dtype,
        "vram_gb": vram_gb,
        "gpu_name": name,
    }


def detect_rocm() -> dict | None:
    """AMD ROCm - Linux only, probed via rocminfo."""
    if platform.system() != "Linux" or not shutil.which("rocminfo"):
        return None
    out = _run_quiet(["rocminfo"], timeout=30)
    if not out or "gfx" not in out:
        return None
    # PyTorch-on-ROCm still exposes the device as "cuda" to user code.
    # float16 is the safe default across RDNA/CDNA generations.
    return {
        "device": "cuda",
        "accelerator": "rocm",
        "dtype": "float16",
        "vram_gb": None,
        "gpu_name": "AMD ROCm GPU",
    }


def detect_mps() -> dict | None:
    """Apple Silicon: Darwin + arm64 implies Metal Performance Shaders."""
    if platform.system() != "Darwin" or platform.machine() != "arm64":
        return None
    # Apple Silicon uses unified memory: the GPU shares system RAM, so we
    # report total RAM as vram_gb - it is the honest budget for model work.
    vram_gb = None
    out = _run_quiet(["sysctl", "-n", "hw.memsize"])
    if out:
        try:
            vram_gb = round(int(out.strip()) / (1024 ** 3), 1)
        except ValueError:
            pass
    return {
        "device": "mps",
        "accelerator": "mps",
        "dtype": "float16",
        "vram_gb": vram_gb,
        "gpu_name": "Apple Silicon (unified memory)",
    }


def build_config(force_cpu: bool) -> dict:
    detected = None if force_cpu else (detect_nvidia() or detect_rocm() or detect_mps())
    if detected is None:
        detected = {
            "device": "cpu",
            "accelerator": "cpu",
            "dtype": "float32",
            "vram_gb": None,
            "gpu_name": None,
        }
    vram = detected["vram_gb"]
    if vram is not None and vram >= 12:
        tier = "gpu-high"
    elif vram is not None and vram > 0:
        tier = "gpu-low"
    else:
        tier = "cpu"
    config = {
        "device": detected["device"],
        "accelerator": detected["accelerator"],
        "dtype": detected["dtype"],
        "vram_gb": detected["vram_gb"],
        "tier": tier,
    }
    CONFIG_PATH.write_text(json.dumps(config, indent=2) + "\n", encoding="utf-8")
    gpu = detected.get("gpu_name") or "none"
    log(f"hardware: {gpu} -> {config}")
    log(f"wrote {CONFIG_PATH.name}")
    return config


# ------------------------------------------------------------------ sync


def _desired_torch_block(config: dict) -> str:
    index = PYTORCH_INDEX.get(config["accelerator"])
    if not index:
        return ""
    name = f"pytorch-{config['accelerator']}"
    return (
        f"{BLOCK_BEGIN}\n"
        "[[tool.uv.index]]\n"
        f'name = "{name}"\n'
        f'url = "{index}"\n'
        "explicit = true\n\n"
        "[tool.uv.sources]\n"
        f'torch = [{{ index = "{name}" }}]\n'
        f'torchvision = [{{ index = "{name}" }}]\n'
        f"{BLOCK_END}\n"
    )


def write_torch_config(config: dict) -> None:
    """Sync the marked machine-local block in pyproject.toml with this machine.

    The block is absent in the committed file and on CPU/MPS machines; on
    CUDA/ROCm machines it pins torch/torchvision to the matching explicit
    PyTorch index. uv does not re-resolve when index/source config changes,
    so uv.lock is deleted whenever the desired block disagrees with the lock.
    """
    text = PYPROJECT_PATH.read_text(encoding="utf-8")
    desired = _desired_torch_block(config)

    # strip any existing generated block
    if BLOCK_BEGIN in text:
        start = text.index(BLOCK_BEGIN)
        end = text.index(BLOCK_END) + len(BLOCK_END)
        text = (text[:start] + text[end:]).rstrip("\n") + "\n"

    if desired and desired not in text:
        text = text.rstrip("\n") + "\n\n" + desired
    new_text = text
    if new_text != PYPROJECT_PATH.read_text(encoding="utf-8"):
        PYPROJECT_PATH.write_text(new_text, encoding="utf-8", newline="\n")
        index = PYTORCH_INDEX.get(config["accelerator"])
        log(f"pyproject.toml machine block -> {index or 'removed (default PyPI)'}")
    else:
        log("pyproject.toml machine block already correct")

    # legacy cleanup: earlier bootstrap versions generated a uv.toml
    if UV_TOML_PATH.exists() and "tools/bootstrap.py" in UV_TOML_PATH.read_text(
        encoding="utf-8", errors="replace"
    ):
        UV_TOML_PATH.unlink()
        log("removed legacy generated uv.toml")

    # Force re-resolution when the lock disagrees with the desired index.
    index = PYTORCH_INDEX.get(config["accelerator"])
    if LOCK_PATH.exists():
        lock_text = LOCK_PATH.read_text(encoding="utf-8", errors="replace")
        lock_uses_pytorch = "download.pytorch.org" in lock_text
        if lock_uses_pytorch != bool(index) or (index and index not in lock_text):
            LOCK_PATH.unlink()
            log("removed uv.lock to force re-resolution against the correct index")


def uv_sync(uv: str, config: dict) -> None:
    write_torch_config(config)
    log("uv sync ...")
    subprocess.run([uv, "sync"], cwd=REPO_ROOT, check=True)


# -------------------------------------------------------------- downloads


def fetch_all(uv: str) -> None:
    """Prefetch every manifest item via tools/fetch_data.py.

    fetch_data.py owns per-item retry (5 attempts, 30s backoff; huggingface_hub
    resumes partial downloads), prints each item's license line, and prints the
    CreativeML OpenRAIL-M use-restriction notice before the SD1.5 download.
    """
    log("prefetching all datasets/models (license lines printed per item)...")
    subprocess.run(
        [uv, "run", "python", str(REPO_ROOT / "tools" / "fetch_data.py"), "all"],
        cwd=REPO_ROOT,
        check=True,
    )


# ------------------------------------------------------------------ main


def main() -> None:
    parser = argparse.ArgumentParser(description="Bootstrap the ML workshop environment.")
    parser.add_argument("--cpu", action="store_true",
                        help="force the CPU tier (for testing low-spec paths)")
    parser.add_argument("--download", action="store_true",
                        help="after syncing, prefetch all datasets/models from the manifest")
    args = parser.parse_args()

    log(f"python {platform.python_version()} on {platform.system()} {platform.machine()}")

    uv = find_uv() or install_uv()
    log(f"uv: {uv}")

    config = build_config(force_cpu=args.cpu)
    if args.cpu and config["tier"] != "cpu":
        sys.exit("[bootstrap] ERROR: --cpu requested but config is not cpu tier.")

    uv_sync(uv, config)

    if args.download:
        fetch_all(uv)

    log("done. Start the course with: uv run jupyter lab")


if __name__ == "__main__":
    main()
